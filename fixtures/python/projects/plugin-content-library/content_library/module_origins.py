"""Source, bytecode-only, built-in, frozen, and extension modules (PY-CAN-MOD-017).

Imports representatives and records ``__spec__.origin`` / ``__file__``
availability.  Demonstrates bytecode magic / invalidation, ABI suffixes,
source-less modules, and stale cache.

Native / C extension context: the extension representative is compiled by
``task build`` as ``content_library/_native_ext.<ext_suffix>``.
Child process context: not needed here (module import is default runtime).

Generated bytecode is produced by ``task generate`` as
``content_library/generated_bytecode/bytecode_only.pyc`` (source-less).
"""

from __future__ import annotations

import importlib.machinery
import importlib.util
import inspect
import pathlib
import sys
import sysconfig


def source_origin() -> dict[str, object]:
    import content_library.entry_declarations as src

    spec = getattr(src, "__spec__", None)
    return {
        "origin": getattr(spec, "origin", None) if spec else None,
        "has_file": hasattr(src, "__file__"),
        "file": getattr(src, "__file__", None),
        "has_source_via_inspect": inspect.getsource(src.ContentItem) is not None,
    }


def bytecode_only_origin() -> dict[str, object]:
    """Load the committed source-less compiled file via SourcelessFileLoader."""
    project = pathlib.Path(__file__).parent
    # Two possible locations for the generated bytecode representative:
    pyc_candidates = [
        project / "generated_bytecode" / "bytecode_only.pyc",
        project / "bytecode_only.pyc",
    ]
    pyc = next((p for p in pyc_candidates if p.exists()), None)
    if pyc is None:
        return {"origin": None, "note": "bytecode not yet generated — run task generate"}
    loader = importlib.machinery.SourcelessFileLoader("content_library.bytecode_only", str(pyc))
    spec = importlib.machinery.ModuleSpec("content_library.bytecode_only", loader, origin=str(pyc))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    try:
        loader.exec_module(mod)
        return {
            "origin": spec.origin,
            "has_file": hasattr(mod, "__file__"),
            "file": getattr(mod, "__file__", None),
            "value": getattr(mod, "VALUE", None),
            "has_source": False,
        }
    finally:
        del sys.modules[spec.name]


def builtin_origin() -> dict[str, object]:
    import sys as builtin_mod

    spec = getattr(builtin_mod, "__spec__", None)
    return {
        "origin": getattr(spec, "origin", None) if spec else "built-in",
        "has_file": hasattr(builtin_mod, "__file__"),
        "expected_origin": "built-in",
    }


def frozen_origin() -> dict[str, object]:
    # ``_frozen_importlib`` and ``importlib._bootstrap`` are frozen in CPython.
    import importlib._bootstrap as frozen_mod

    spec = getattr(frozen_mod, "__spec__", None)
    origin = getattr(spec, "origin", None) if spec else None
    return {
        "name": frozen_mod.__name__,
        "origin": origin,
        "expected": "frozen",
        "has_file": hasattr(frozen_mod, "__file__"),
    }


def extension_origin() -> dict[str, object]:
    suffix = sysconfig.get_config_var("EXT_SUFFIX")
    project = pathlib.Path(__file__).parent
    # Look for compiled extension matching suffix.
    candidate = next(project.glob(f"_native_ext*{suffix}"), None) if suffix else None
    if candidate is None:
        return {"origin": None, "note": "extension not yet built — run task build", "suffix": suffix}
    # Actually import the extension via its ExtensionFileLoader / import system.
    import importlib

    # Ensure content_library package is importable, then import the extension.
    # Use import_module which triggers ExtensionFileLoader.
    ext_mod = importlib.import_module("content_library._native_ext")
    spec = getattr(ext_mod, "__spec__", None)
    origin = getattr(spec, "origin", None) if spec else str(candidate)
    return {
        "origin": origin,
        "has_file": hasattr(ext_mod, "__file__"),
        "file": getattr(ext_mod, "__file__", None),
        "suffix": suffix,
        "is_extension": str(origin).endswith(suffix or ".so") if origin else str(candidate).endswith(suffix or ".so"),
        "imported": True,
        "hello": ext_mod.hello(),  # type: ignore[attr-defined]
        "loader": type(spec.loader).__name__ if spec and spec.loader else None,
    }


def _pyc_flags(data: bytes) -> int | None:
    """Return the PEP 552 bit field from a ``.pyc`` header, or ``None``."""
    if len(data) < 8:
        return None
    return int.from_bytes(data[4:8], "little")


def _describe_flags(flags: int | None) -> str | None:
    """Map a ``.pyc`` bit field to its invalidation kind (PEP 552)."""
    if flags is None:
        return None
    if flags == 0:
        return "timestamp"
    if flags == 1:
        return "unchecked-hash"
    if flags == 3:
        return "checked-hash"
    return f"flags={flags}"


def bytecode_invalidation_demo() -> dict[str, object]:
    """Instantiate the real PEP 552 invalidation variants and read them back.

    Rather than labelling the invalidation modes, this compiles a source file
    under each mode and reads the resulting ``.pyc`` header, so the timestamp,
    unchecked-hash, and checked-hash variants are actual artifacts (flags 0, 1,
    3).  Compilation happens in a temporary directory and mutates no tracked
    source.
    """
    import py_compile
    import tempfile

    project = pathlib.Path(__file__).parent
    pyc = project / "generated_bytecode" / "bytecode_only.pyc"
    try:
        default_mode = py_compile._get_default_invalidation_mode()  # type: ignore[attr-defined]
    except AttributeError:
        default_mode = py_compile.PycInvalidationMode.TIMESTAMP  # type: ignore

    committed_flags = _pyc_flags(pyc.read_bytes()) if pyc.exists() else None

    variants: dict[str, dict[str, object]] = {}
    with tempfile.TemporaryDirectory() as tmp:
        src = pathlib.Path(tmp) / "invalidation_src.py"
        src.write_text("VALUE = 'invalidation-source'\n")
        for name, mode in [
            ("timestamp", py_compile.PycInvalidationMode.TIMESTAMP),
            ("unchecked_hash", py_compile.PycInvalidationMode.UNCHECKED_HASH),
            ("checked_hash", py_compile.PycInvalidationMode.CHECKED_HASH),
        ]:
            out = pathlib.Path(tmp) / f"{name}.pyc"
            py_compile.compile(str(src), cfile=str(out), invalidation_mode=mode)
            data = out.read_bytes()
            flags = _pyc_flags(data)
            variants[name] = {
                "flags": flags,
                "kind": _describe_flags(flags),
                # Timestamp header stores mtime+size in bytes 8:16; the hash
                # headers store the 8-byte source hash in the same field.
                "header_field": data[8:16].hex(),
            }

    return {
        "magic_number": importlib.util.MAGIC_NUMBER.hex(),
        "cache_tag": sys.implementation.cache_tag,
        "py_compile_default": str(default_mode).split(".")[-1],
        "py_compile_default_repr": repr(default_mode),
        "committed_pyc": str(pyc),
        "committed_pyc_flags": committed_flags,
        "committed_pyc_invalidation": _describe_flags(committed_flags),
        "invalidation_variants": variants,
    }


def stale_cache_demo() -> dict[str, object]:
    """Demonstrate real stale-cache detection under both invalidation modes.

    Timestamp mode: moving the source mtime past the cached ``.pyc`` makes the
    machinery recompile on the next import.  Checked-hash mode: changing the
    source *content* while restoring its mtime defeats the timestamp check, but
    the checked-hash header still forces recompilation from the new source.
    Both run in temporary directories and mutate no tracked source.
    """
    import os
    import tempfile
    import time
    import py_compile

    timestamp_result: dict[str, object] = {}
    with tempfile.TemporaryDirectory() as tmp:
        tmpp = pathlib.Path(tmp)
        src = tmpp / "stale_ts_mod.py"
        src.write_text("VALUE = 'original'\n")
        cache = pathlib.Path(importlib.util.cache_from_source(str(src)))
        sys.path.insert(0, str(tmpp))
        try:
            importlib.invalidate_caches()
            before = importlib.import_module("stale_ts_mod").VALUE  # type: ignore[attr-defined]
            first_mtime = cache.stat().st_mtime_ns
            src.write_text("VALUE = 'updated'\n")
            future = time.time() + 10
            os.utime(src, (future, future))
            sys.modules.pop("stale_ts_mod", None)
            importlib.invalidate_caches()
            after = importlib.import_module("stale_ts_mod").VALUE  # type: ignore[attr-defined]
            timestamp_result = {
                "before": before,
                "after": after,
                "recompiled": cache.stat().st_mtime_ns != first_mtime,
            }
        finally:
            if str(tmpp) in sys.path:
                sys.path.remove(str(tmpp))
            sys.modules.pop("stale_ts_mod", None)
            importlib.invalidate_caches()

    hash_result: dict[str, object] = {}
    with tempfile.TemporaryDirectory() as tmp:
        tmpp = pathlib.Path(tmp)
        src = tmpp / "stale_hash_mod.py"
        src.write_text("VALUE = 'hash-original'\n")
        original_stat = src.stat()
        py_compile.compile(
            str(src), invalidation_mode=py_compile.PycInvalidationMode.CHECKED_HASH
        )
        sys.path.insert(0, str(tmpp))
        try:
            importlib.invalidate_caches()
            before = importlib.import_module("stale_hash_mod").VALUE  # type: ignore[attr-defined]
            src.write_text("VALUE = 'hash-updated'\n")
            os.utime(src, (original_stat.st_atime, original_stat.st_mtime))
            sys.modules.pop("stale_hash_mod", None)
            importlib.invalidate_caches()
            after = importlib.import_module("stale_hash_mod").VALUE  # type: ignore[attr-defined]
            hash_result = {
                "before": before,
                "after": after,
                "detected_via_hash": after == "hash-updated",
            }
        finally:
            if str(tmpp) in sys.path:
                sys.path.remove(str(tmpp))
            sys.modules.pop("stale_hash_mod", None)
            importlib.invalidate_caches()

    return {
        "timestamp_invalidation": timestamp_result,
        "checked_hash_invalidation": hash_result,
    }


