import 'dart:convert';

import 'package:build/build.dart';
import 'package:dart_style/dart_style.dart';

import 'asset_paths.dart';

final _formatter = DartFormatter(
  languageVersion: DartFormatter.latestLanguageVersion,
);

/// Second, transitive stage of the catalog builder chain
/// (DART-CAN-BUILD-003).
///
/// Its input extension (`.catalog.index.json`) is `CatalogIndexBuilder`'s
/// *output*, not the original `.catalog.json` source, so build_runner can
/// only schedule this builder after that one runs. The committed
/// `.catalog.g.dart` library is this stage's output, the only one of the
/// two committed to source control.
///
/// [includeCodes] is read from `build.yaml`'s `options:` block for this
/// builder, demonstrating a builder option that changes generated content:
/// when `false`, generated tool descriptions omit each tool's product code.
class CatalogDataBuilder implements Builder {
  const CatalogDataBuilder({required this.includeCodes});

  final bool includeCodes;

  @override
  Map<String, List<String>> get buildExtensions => const {
    '.catalog.index.json': ['.catalog.g.dart'],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    final input = buildStep.inputId;
    final index =
        jsonDecode(await buildStep.readAsString(input)) as Map<String, dynamic>;
    final crateId = index['crateId'] as String;
    final tools = (index['tools'] as List<dynamic>)
        .cast<Map<String, dynamic>>();

    final entries = tools
        .map((tool) {
          final name = tool['name'] as String;
          final code = tool['code'] as String;
          final description = includeCodes ? '$name ($code)' : name;
          return "  CatalogTool('$name', '$code', '$description'),";
        })
        .join('\n');

    final output = withSuffix(input, '.catalog.index.json', '.catalog.g.dart');
    final source =
        '''
// GENERATED CODE - DO NOT MODIFY BY HAND
//
// Generated by CatalogDataBuilder from ${input.path}, itself generated by
// CatalogIndexBuilder from the non-Dart bench_catalog.catalog.json input.
// This is a transitive builder: its input extension is another builder's
// output extension, not a source file extension.
// ignore_for_file: type=lint

/// A catalog entry produced by the config-driven catalog builder chain.
class CatalogTool {
  const CatalogTool(this.name, this.code, this.description);

  final String name;
  final String code;
  final String description;
}

/// Generated from the `crateId` field of bench_catalog.catalog.json.
const String benchCatalogCrateId = '$crateId';

/// Generated, alphabetically-by-code-sorted tool list.
const List<CatalogTool> benchCatalogTools = [
$entries
];
''';
    await buildStep.writeAsString(output, _formatter.format(source));
  }
}
