"""Source, bytecode-only, built-in, frozen, and extension modules (PY-CAN-MOD-017).

Imports representatives and records ``__spec__.origin`` / ``__file__``
availability.  Demonstrates bytecode magic / invalidation, ABI suffixes,
source-less modules, and stale cache.

Native / C extension context: the extension representative is compiled by
``task build`` as ``content_library/_native_ext.<ext_suffix>``.
Child process context: not needed here (module import is default runtime).

Generated bytecode is produced by ``task generate`` as
``content_library/generated_bytecode/bytecode_only.pyc`` (source-less).
"""

from __future__ import annotations

import importlib.machinery
import importlib.util
import inspect
import pathlib
import sys
import sysconfig


def source_origin() -> dict[str, object]:
    import content_library.entry_declarations as src

    spec = getattr(src, "__spec__", None)
    return {
        "origin": getattr(spec, "origin", None) if spec else None,
        "has_file": hasattr(src, "__file__"),
        "file": getattr(src, "__file__", None),
        "has_source_via_inspect": inspect.getsource(src.ContentItem) is not None,
    }


def bytecode_only_origin() -> dict[str, object]:
    """Load the committed source-less compiled file via SourcelessFileLoader."""
    project = pathlib.Path(__file__).parent
    # Two possible locations for the generated bytecode representative:
    pyc_candidates = [
        project / "generated_bytecode" / "bytecode_only.pyc",
        project / "bytecode_only.pyc",
    ]
    pyc = next((p for p in pyc_candidates if p.exists()), None)
    if pyc is None:
        return {"origin": None, "note": "bytecode not yet generated — run task generate"}
    loader = importlib.machinery.SourcelessFileLoader("content_library.bytecode_only", str(pyc))
    spec = importlib.machinery.ModuleSpec("content_library.bytecode_only", loader, origin=str(pyc))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    try:
        loader.exec_module(mod)
        return {
            "origin": spec.origin,
            "has_file": hasattr(mod, "__file__"),
            "file": getattr(mod, "__file__", None),
            "value": getattr(mod, "VALUE", None),
            "has_source": False,
        }
    finally:
        del sys.modules[spec.name]


def builtin_origin() -> dict[str, object]:
    import sys as builtin_mod

    spec = getattr(builtin_mod, "__spec__", None)
    return {
        "origin": getattr(spec, "origin", None) if spec else "built-in",
        "has_file": hasattr(builtin_mod, "__file__"),
        "expected_origin": "built-in",
    }


def frozen_origin() -> dict[str, object]:
    # ``_frozen_importlib`` and ``importlib._bootstrap`` are frozen in CPython.
    import importlib._bootstrap as frozen_mod

    spec = getattr(frozen_mod, "__spec__", None)
    origin = getattr(spec, "origin", None) if spec else None
    return {
        "name": frozen_mod.__name__,
        "origin": origin,
        "expected": "frozen",
        "has_file": hasattr(frozen_mod, "__file__"),
    }


def extension_origin() -> dict[str, object]:
    suffix = sysconfig.get_config_var("EXT_SUFFIX")
    project = pathlib.Path(__file__).parent
    # Look for compiled extension matching suffix.
    candidate = next(project.glob(f"_native_ext*{suffix}"), None) if suffix else None
    if candidate is None:
        return {"origin": None, "note": "extension not yet built — run task build", "suffix": suffix}
    # Actually import the extension via its ExtensionFileLoader / import system.
    import importlib

    # Ensure content_library package is importable, then import the extension.
    # Use import_module which triggers ExtensionFileLoader.
    ext_mod = importlib.import_module("content_library._native_ext")
    spec = getattr(ext_mod, "__spec__", None)
    origin = getattr(spec, "origin", None) if spec else str(candidate)
    return {
        "origin": origin,
        "has_file": hasattr(ext_mod, "__file__"),
        "file": getattr(ext_mod, "__file__", None),
        "suffix": suffix,
        "is_extension": str(origin).endswith(suffix or ".so") if origin else str(candidate).endswith(suffix or ".so"),
        "imported": True,
        "hello": ext_mod.hello(),  # type: ignore[attr-defined]
        "loader": type(spec.loader).__name__ if spec and spec.loader else None,
    }


def bytecode_invalidation_demo() -> dict[str, object]:
    """Demonstrate bytecode magic and actual invalidation (PEP 552)."""
    import py_compile

    project = pathlib.Path(__file__).parent
    pyc = project / "generated_bytecode" / "bytecode_only.pyc"
    # Real default on this interpreter; CPython 3.14 reports TIMESTAMP.
    try:
        default_mode = py_compile._get_default_invalidation_mode()  # type: ignore[attr-defined]
    except AttributeError:
        default_mode = py_compile.PycInvalidationMode.TIMESTAMP  # type: ignore

    # Inspect actual committed pyc header flags (0 = timestamp, 1 = unchecked hash, 3 = checked hash per PEP 552).
    header_flags = None
    header_desc = None
    if pyc.exists():
        data = pyc.read_bytes()
        if len(data) >= 8:
            import struct

            flags = int.from_bytes(data[4:8], "little")
            header_flags = flags
            if flags == 0:
                header_desc = "timestamp"
            elif flags & 1:
                header_desc = "hash-based"
            else:
                header_desc = f"flags={flags}"

    return {
        "magic_number": importlib.util.MAGIC_NUMBER.hex(),
        "cache_tag": sys.implementation.cache_tag,
        "bytecode_invalidation_modes": ["timestamp", "hash (checked/unchecked)"],
        "py_compile_default": str(default_mode).split(".")[-1],
        "py_compile_default_repr": repr(default_mode),
        "committed_pyc": str(pyc),
        "committed_pyc_flags": header_flags,
        "committed_pyc_invalidation": header_desc,
        "stale_cache_note": "stale cache: .pyc mtime/size mismatch (timestamp) or hash mismatch (hash) causes regeneration",
    }


def stale_cache_demo() -> str:
    return "stale cache: .pyc newer than .py or hash mismatch causes regeneration or Sourceless fallback"


def missing_file_demo() -> str:
    return "built-in and frozen modules lack __file__; source-less modules have origin pointing to .pyc"
