import 'package:analyzer/dart/element/element.dart';
import 'package:build/build.dart';
import 'package:source_gen/source_gen.dart';

import '../annotations.dart';

/// Emits a `TorqueWrenchSummary`-shaped extension for each class annotated
/// with [ToolSummary], as the `part` output resolved by `toolSummaryBuilder`.
///
/// The emitted extension calls a private top-level function declared in the
/// annotated class's own library and reads a private field declared on the
/// annotated class itself. Both references compile only because a `part`
/// shares its library's private namespace with the file it is `part of`.
class ToolSummaryGenerator extends GeneratorForAnnotation<ToolSummary> {
  const ToolSummaryGenerator();

  @override
  String generateForAnnotatedElement(
    Element element,
    ConstantReader annotation,
    BuildStep buildStep,
  ) {
    if (element is! ClassElement) {
      throw InvalidGenerationSourceError(
        '@ToolSummary can only annotate classes.',
        element: element,
      );
    }

    final className = element.name!;
    final fields = element.fields.where((field) => !field.isStatic).toList();
    final privateMatches = fields.where((field) => field.name!.startsWith('_'));
    final labelMatches = fields.where((field) => field.name == 'label');

    final privateFieldName =
        (privateMatches.isEmpty ? fields.first : privateMatches.first).name!;
    final labelFieldName =
        (labelMatches.isEmpty ? fields.first : labelMatches.first).name!;

    return '''
/// Generated by [ToolSummaryGenerator] from the [ToolSummary] annotation on
/// [$className]. `_normalizeLabel` and `$privateFieldName` are private
/// declarations from $className's own library, reachable here only because
/// this file is a `part of` that library.
extension ${className}Summary on $className {
  String summary() =>
      '\${_normalizeLabel($labelFieldName)} @ \${$privateFieldName.toStringAsFixed(1)} Nm';
}
''';
  }
}
