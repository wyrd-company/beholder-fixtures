import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

// Rolled declaration whose public entity layout differs from source.
// Source has separate files: re-export-chain-a, re-export-chain-b, barrel.
// Rolled output collapses the re-export chain and inlines types.
const rolled = `// Generated by generator/generate.mjs — do not edit manually.
// Rolled declaration collapsing re-export chains and private names.

export interface AtlasPoint {
  x: number;
  y: number;
}

export declare function formatPoint(p: AtlasPoint): string;

export interface ShelfMarker {
  tag: string;
  point: AtlasPoint;
}

export interface BeaconCatalogItem {
  id: string;
  label: string;
}

export declare function describeCatalog(item: BeaconCatalogItem): string;

export declare function createBeaconEntry(id: string): {
  item: BeaconCatalogItem;
  token: unknown;
};

// Declaration rollup: re-export chain collapsed into single module, private names inlined.
`;

const platformGenerated = `// Generated typed platform module — condition-selected browser/server/native via generated source.

export interface PlatformGeneratedMarker {
  source: "generated-platform";
  platform: "browser" | "server" | "native";
  env: "development" | "production";
}

export declare function describeGeneratedPlatform(
  platform: PlatformGeneratedMarker["platform"],
): string;
`;

const pkgJson = `{
  "name": "@fixtures/generated-platform-pkg",
  "version": "1.0.0",
  "private": true,
  "type": "module",
  "description": "Generated typed package for platform variants",
  "exports": {
    ".": {
      "types": "./index.d.ts",
      "import": "./index.js"
    }
  }
}
`;

const pkgIndexJs = `export function describeGeneratedPlatform(platform) {
  return \`generated:\${platform}\`;
}
`;

mkdirSync(join(root, "generated"), { recursive: true });
mkdirSync(join(root, "generated/platform-generated"), { recursive: true });

writeFileSync(join(root, "generated/rolled.d.ts"), rolled);
writeFileSync(
  join(root, "generated/platform-generated/index.d.ts"),
  platformGenerated,
);
writeFileSync(join(root, "generated/platform-generated/package.json"), pkgJson);
writeFileSync(join(root, "generated/platform-generated/index.js"), pkgIndexJs);

console.log("Generated rolled and platform outputs.");
